"""Build a Nasdara bear_territories.xml from Nasdara-authored wilderness zones.

usage: python -I make_bear_zones.py <world_mid_m> <out.xml> [--spawn-buffer 1000] [--merge 500] [--radius 200]

The mission ships Livonia's bear file unchanged, so its 85 zones cover only the
south-west 12.8 km square of a ~16 km map and land on whatever terrain is there.
Bohemia did author wolf, mouflon and goat territories for Nasdara's own terrain,
and those are wild ground by construction, so their zone centres are the anchors.

Rules applied, in order:
  1. Anchors: every wolf, mouflon and goat zone centre.
  2. Quadrants: the bear zone, radius included, must lie outside the north-west
     quadrant (x < mid and z > mid), i.e. in the southern or eastern half.
  3. Spawn buffer: at least --spawn-buffer metres from every fresh-spawn bubble in
     cfgplayerspawnpoints.xml, so a fresh character does not land next to a bear.
  4. Merge: anchors closer than --merge metres collapse into one zone (first wins,
     wolves first since they carry the widest wilderness radii).
Zone attributes follow every official bear file: name Graze, counts 0, radius fixed.
"""
import math
import re
import sys

ROOT = __file__.rsplit("!aux", 1)[0]
NASDARA_DEFAULT = ROOT + "DEFAULT/dayzxb_missions/dayzOffline.nasdara/"
NASDARA_REMOTE = ROOT + "remote/dayzxb_missions/dayzOffline.nasdara/"
ANCHOR_FILES = [
    ("wolf", NASDARA_DEFAULT + "env/wolf_territories.xml"),
    ("mouflon", NASDARA_REMOTE + "env/mouflon_territories.xml"),
    ("goat", NASDARA_REMOTE + "env/goat_territories.xml"),
]


def zones(path):
    text = open(path, encoding="utf-8").read()
    return [dict(re.findall(r'(\w+)="([^"]*)"', t)) for t in re.findall(r"<zone\b[^>]*/>", text)]


def main():
    args = sys.argv[1:]
    opts = {"--spawn-buffer": 1000.0, "--merge": 500.0, "--radius": 200.0}
    for key in list(opts):
        if key in args:
            i = args.index(key)
            opts[key] = float(args[i + 1])
            del args[i:i + 2]
    mid, out = float(args[0]), args[1]
    buffer, merge, radius = opts["--spawn-buffer"], opts["--merge"], opts["--radius"]

    spawn_xml = open(NASDARA_REMOTE + "cfgplayerspawnpoints.xml", encoding="utf-8").read()
    fresh = spawn_xml.split("<fresh>", 1)[1].split("</fresh>", 1)[0]
    spawns = [(float(x), float(z)) for x, z in re.findall(r'<pos x="([-\d.]+)" z="([-\d.]+)"', fresh)]

    kept, dropped = [], {"north-west quadrant": 0, "spawn buffer": 0, "merged": 0}
    for source, path in ANCHOR_FILES:
        for a in zones(path):
            x, z = float(a["x"]), float(a["z"])
            if x - radius < mid and z + radius > mid:
                dropped["north-west quadrant"] += 1
                continue
            if any(math.hypot(x - sx, z - sz) < buffer for sx, sz in spawns):
                dropped["spawn buffer"] += 1
                continue
            if any(math.hypot(x - kx, z - kz) < merge for kx, kz, _ in kept):
                dropped["merged"] += 1
                continue
            kept.append((x, z, source))

    quadrant = lambda x, z: ("N" if z > mid else "S") + ("E" if x >= mid else "W")
    counts = {}
    for x, z, _ in kept:
        counts[quadrant(x, z)] = counts.get(quadrant(x, z), 0) + 1
    by_source = {}
    for _, _, s in kept:
        by_source[s] = by_source.get(s, 0) + 1

    lines = [
        '<?xml version="1.0" encoding="UTF-8" standalone="yes" ?>',
        "<!-- Nasdara bear territories, generated by !aux/make_bear_zones.py from Bohemia's Nasdara wolf, mouflon",
        f"     and goat zones. Southern and eastern half only (nothing in the north-west quadrant, mid {mid:.0f} m),",
        f"     at least {buffer:.0f} m from every fresh-spawn bubble, anchors closer than {merge:.0f} m merged. The mission's",
        "     own bear_territories.xml is Livonia's file unchanged and covers only the south-west 12.8 km. -->",
        "<territory-type>",
        '    <territory color="4287365357">',
    ]
    for x, z, source in sorted(kept, key=lambda k: (quadrant(k[0], k[1]), k[0])):
        lines.append(f'        <zone name="Graze" smin="0" smax="0" dmin="0" dmax="0" x="{x:.2f}" z="{z:.2f}" r="{radius:.0f}"/>'
                     f"  <!-- {quadrant(x, z)}, {source} -->")
    lines += ["    </territory>", "</territory-type>", ""]
    open(out, "w", encoding="utf-8", newline="\n").write("\n".join(lines))

    print(f"spawn bubbles (fresh): {len(spawns)}, of which west of mid: {sum(1 for sx, _ in spawns if sx < mid)}")
    print(f"kept {len(kept)} zones  by quadrant {counts}  by source {by_source}")
    print(f"dropped {dropped}")
    xs = [k[0] for k in kept]; zs = [k[1] for k in kept]
    print(f"extent x {min(xs):.0f}..{max(xs):.0f}  z {min(zs):.0f}..{max(zs):.0f}")
    nearest_spawn = min(math.hypot(x - sx, z - sz) for x, z, _ in kept for sx, sz in spawns)
    print(f"nearest bear zone centre to a spawn bubble: {nearest_spawn:.0f} m")


if __name__ == "__main__":
    main()

"""
Survivor board: turns the server's admin logs into the in-game messages that greet a
player on connect with the longest-living characters and the last death.

    python scripts/survivors.py                                   # ingest new logs, update the ledger, render
    python scripts/survivors.py --mission dayzOffline.nasdara     # first run, or after a map switch
    python scripts/survivors.py --since 2026-12-01                # ignore logs older than a wipe
    python scripts/survivors.py --rebuild                         # recompute the ledger from every archived log

Inputs
  * nitrado-logs/**/*.ADM   the archived admin logs (gitignored; pull them first). Folders whose
                            name starts with "!scrap" are skipped. The same file name in two
                            folders is read once, taking the larger copy.
  * data/survivors.json     the ledger: which logs were ingested, every character's time alive,
                            every death. History survives logs that are no longer around, so a
                            log is read once and only new files are ingested on later runs.

Output
  * remote/dayzxb_missions/<mission>/db/messages.xml   up to five onconnect messages, each shown
    once, one minute apart, starting a minute after the player connects: the three longest-living
    characters, the last death, then a note that the board refreshes at restart. The engine reads
    the file at server start, so the board changes when the next deploy restarts the server.
    Nothing else may live in this file; it is rewritten whole.

What counts
  * A character belongs to the player's id hash, never the name. Names can change, so the board
    shows the latest one seen.
  * Time alive is connected time, like the game's own survival stat: the sum of connect-to-
    disconnect intervals. A character still connected when an instance ends (restart, crash)
    counts to the log's last line.
  * A character ends at a "(DEAD)" line, which names the killer where there is one, and the
    player's next character starts there. It also ends silently when a connect lands farther than
    RESET_DISTANCE from the last clean logout position: the engine restores the exact position on
    login, so a different place means a death we never saw (a log gap) or a wipe. A character
    older than the archive counts from its first logged connect.
"""
import argparse
import json
import math
import os
import re
import sys
from datetime import datetime, timedelta
from xml.sax.saxutils import escape

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LOGS_DIR = os.path.join(ROOT, "nitrado-logs")
LEDGER_PATH = os.path.join(ROOT, "data", "survivors.json")
MISSIONS_DIR = os.path.join(ROOT, "remote", "dayzxb_missions")

MARKER = "Generated by scripts/survivors.py"
TOP = 3
RESET_DISTANCE = 25.0  # metres between a login and the last clean logout that means a new character
TIME_FORMAT = "%Y-%m-%dT%H:%M:%S"

HEADER = re.compile(r"^AdminLog started on (\d{4}-\d\d-\d\d) at (\d\d:\d\d:\d\d)")
LINE = re.compile(r"^(\d\d):(\d\d):(\d\d) \| (.*)$")
PLAYER = re.compile(
    r'Player "(?P<name>[^"]*)"(?P<dead> \(DEAD\))? \(id=(?P<id>[0-9A-Fa-f]+)'
    r"(?: pos=<(?P<x>-?[\d.]+), (?P<y>-?[\d.]+), (?P<z>-?[\d.]+)>)?\)"
)
KILLER = re.compile(r'^killed by Player "(?P<name>[^"]*)"')
# Class-name prefixes the engine writes after "killed by", and the words the board uses.
ANIMALS = (
    ("Animal_UrsusArctos", "a bear"),
    ("Animal_CanisLupus", "a wolf"),
    ("Animal_CanisFamiliaris", "a wild dog"),
    ("Animal_SusScrofa", "a boar"),
    ("Animal_BosTaurus", "a cow"),
)


def fmt_time(t):
    return t.strftime(TIME_FORMAT)


def parse_time(s):
    return datetime.strptime(s, TIME_FORMAT)


def fmt_duration(seconds):
    minutes = int(seconds) // 60
    if minutes < 1:
        return "under a minute"
    days, rest = divmod(minutes, 24 * 60)
    hours, minutes = divmod(rest, 60)
    if days:
        return f"{days} d {hours} h"
    if hours:
        return f"{hours} h {minutes} m"
    return f"{minutes} m"


def distance(a, b):
    return math.hypot(a[0] - b[0], a[1] - b[1])


def describe_cause(tail):
    """Turn the rest of a (DEAD) line into the board's words. Unknown forms are kept as written."""
    m = KILLER.match(tail)
    if m:
        return f"killed by {m.group('name')}"
    if tail.startswith("killed by Zmb"):
        return "killed by an infected"
    for prefix, noun in ANIMALS:
        if tail.startswith("killed by " + prefix):
            return f"killed by {noun}"
    if tail.startswith("killed by explosion"):
        return "killed by an explosion"
    if tail.startswith("killed by FallDamage"):
        return "died from a fall"
    if tail.startswith("committed suicide"):
        return "committed suicide"
    if tail.startswith("died"):
        return "died"
    print(f"  note: unrecognised death line kept verbatim: {tail!r}")
    return tail.split(" Stats>")[0].rstrip(".") or "died"


# --- logs -----------------------------------------------------------------------------------


def find_logs(logs_dir):
    """Map each ADM file name to its path, skipping scrap folders and keeping the larger duplicate."""
    found = {}
    for dirpath, dirnames, filenames in os.walk(logs_dir):
        dirnames[:] = [d for d in dirnames if not d.startswith("!scrap")]
        for fn in filenames:
            if not fn.upper().endswith(".ADM"):
                continue
            path = os.path.join(dirpath, fn)
            if fn not in found or os.path.getsize(path) > os.path.getsize(found[fn]):
                found[fn] = path
    return found


def log_start(path):
    """The instance start time from the file header, or None for a file without one."""
    with open(path, encoding="utf-8", errors="replace") as f:
        for _ in range(20):
            m = HEADER.match(f.readline())
            if m:
                return parse_time(f"{m.group(1)}T{m.group(2)}")
    return None


def read_log(path):
    """Yield (time, body) for every timestamped line, carrying the date across midnight.

    Lines carry only a clock time; the date comes from the header and advances whenever the
    clock goes backwards, which in a sequential log only happens at midnight.
    """
    prev = None
    with open(path, encoding="utf-8", errors="replace") as f:
        for raw in f:
            line = raw.rstrip("\r\n")
            h = HEADER.match(line)
            if h:
                prev = parse_time(f"{h.group(1)}T{h.group(2)}")
                continue
            m = LINE.match(line)
            if not m or prev is None:
                continue
            t = prev.replace(hour=int(m.group(1)), minute=int(m.group(2)), second=int(m.group(3)))
            if t < prev:
                t += timedelta(days=1)
            prev = t
            yield t, m.group(4)


# --- ledger ---------------------------------------------------------------------------------


def empty_ledger():
    return {"mission": None, "since": None, "files": {}, "players": {}}


def load_ledger(path):
    if not os.path.exists(path):
        return empty_ledger()
    with open(path, encoding="utf-8") as f:
        ledger = json.load(f)
    for key, value in empty_ledger().items():
        ledger.setdefault(key, value)
    return ledger


def save_ledger(ledger, path):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        json.dump(ledger, f, indent=2, sort_keys=True)
        f.write("\n")


def new_player(name, t):
    return {
        "name": name,
        "since": fmt_time(t),      # when the current character started
        "alive_seconds": 0,        # connected time of the current character
        "last_seen": fmt_time(t),
        "last_pos": None,
        "clean_logout": False,     # True after a logged disconnect, so last_pos is exact
        "deaths": [],
        "resets": [],              # characters that ended without a (DEAD) line
    }


def ingest(ledger, path):
    """Fold one admin log into the ledger. Returns (start, end) of the lines read."""
    players = ledger["players"]
    online = {}  # id -> datetime the current session started
    start = end = None
    for t, body in read_log(path):
        start = start or t
        end = t
        matches = list(PLAYER.finditer(body))
        if not matches:
            continue
        for m in matches:
            players.setdefault(m["id"], new_player(m["name"], t))
        first = matches[0]
        if first.start() == 0:
            pid = first["id"]
            p = players[pid]
            pos = [float(first["x"]), float(first["y"]), float(first["z"])] if first["x"] else None
            tail = body[first.end():].strip()
            session = (t - online[pid]).total_seconds() if pid in online else 0
            if first["dead"]:
                p["deaths"].append({
                    "at": fmt_time(t),
                    "name": first["name"],
                    "alive_seconds": int(p["alive_seconds"] + session),
                    "cause": describe_cause(tail),
                })
                p["since"] = fmt_time(t)
                p["alive_seconds"] = 0
                p["clean_logout"] = False
                if pid in online:
                    online[pid] = t  # the next character spawns within this session
            elif tail == "is connected" and pid not in online:
                if p["clean_logout"] and pos and p["last_pos"] and distance(pos, p["last_pos"]) > RESET_DISTANCE:
                    p["resets"].append({"at": fmt_time(t), "alive_seconds": p["alive_seconds"],
                                        "from": p["last_pos"][:2], "to": pos[:2]})
                    p["since"] = fmt_time(t)
                    p["alive_seconds"] = 0
                online[pid] = t
            elif tail == "has been disconnected" and pid in online:
                p["alive_seconds"] += int(session)
                p["clean_logout"] = True
                del online[pid]
            p["last_seen"] = fmt_time(t)
        for m in matches:
            q = players[m["id"]]
            q["name"] = m["name"]
            if m["x"]:
                q["last_pos"] = [float(m["x"]), float(m["y"]), float(m["z"])]
    # An instance that stops with players on it logs no disconnects; their time counts to the end.
    for pid, since in online.items():
        p = players[pid]
        p["alive_seconds"] += int((end - since).total_seconds())
        p["clean_logout"] = False
        p["last_seen"] = fmt_time(end)
    return start, end


# --- board ----------------------------------------------------------------------------------


def board_lines(ledger):
    players = ledger["players"].values()
    living = sorted((p for p in players if p["alive_seconds"] > 0), key=lambda p: -p["alive_seconds"])
    labels = ("Longest alive", "2nd longest", "3rd longest")
    lines = [f"{label}: {p['name']}, {fmt_duration(p['alive_seconds'])}" for label, p in zip(labels, living[:TOP])]
    deaths = [d for p in players for d in p["deaths"]]
    if deaths:
        d = max(deaths, key=lambda d: d["at"])
        lines.append(f"Last death: {d['name']}, {d['cause']} after {fmt_duration(d['alive_seconds'])}")
    if lines:
        lines.append("Survivor board refreshes when the server restarts")
    return lines


def render(lines, as_of, path):
    out = [
        '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>',
        f"<!-- {MARKER} from data/survivors.json; rerun the script instead of editing.",
        f"     Board as of {as_of} server time, the last log line ingested. -->",
        "<messages>",
    ]
    for minute, text in enumerate(lines, start=1):
        out += [
            "    <message>",
            f"        <delay>{minute}</delay>",
            "        <onconnect>1</onconnect>",
            f"        <text>{escape(text)}</text>",
            "    </message>",
        ]
    out.append("</messages>")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")


def is_generated(path):
    if not os.path.exists(path):
        return False
    with open(path, encoding="utf-8", errors="replace") as f:
        return MARKER in f.read(500)


# --- main -----------------------------------------------------------------------------------


def rel(path):
    return os.path.relpath(path, ROOT).replace(os.sep, "/")


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--mission", help="mission folder that gets the board, e.g. dayzOffline.nasdara (remembered)")
    ap.add_argument("--since", help="ignore logs that start before this date, YYYY-MM-DD (remembered)")
    ap.add_argument("--rebuild", action="store_true", help="forget every ingested log and read the archive again")
    ap.add_argument("--logs", default=LOGS_DIR, help=argparse.SUPPRESS)
    ap.add_argument("--ledger", default=LEDGER_PATH, help=argparse.SUPPRESS)
    ap.add_argument("--missions-dir", default=MISSIONS_DIR, help=argparse.SUPPRESS)
    args = ap.parse_args()

    ledger = load_ledger(args.ledger)
    mission = args.mission or ledger["mission"]
    if not mission:
        sys.exit("First run: name the mission that gets the board, e.g. --mission dayzOffline.nasdara")
    out_dir = os.path.join(args.missions_dir, mission, "db")
    if not os.path.isdir(out_dir):
        sys.exit(f"{rel(out_dir)} is not a folder; the board needs the mission's db/ under remote/")
    out_path = os.path.join(out_dir, "messages.xml")
    if os.path.exists(out_path) and not is_generated(out_path):
        sys.exit(f"{rel(out_path)} was not written by this script; move it away, the board owns that file")

    rebuild = args.rebuild
    if ledger["mission"] and mission != ledger["mission"]:
        old = os.path.join(args.missions_dir, ledger["mission"], "db", "messages.xml")
        if is_generated(old):
            os.remove(old)
            print(f"removed {rel(old)}: the board moved to {mission}")
        print(f"mission changed from {ledger['mission']} to {mission}: characters start over")
        rebuild = True
    if args.since:
        datetime.strptime(args.since, "%Y-%m-%d")
        if args.since != ledger["since"]:
            rebuild = True
    since = args.since or ledger["since"]
    if rebuild:
        ledger = {"mission": mission, "since": since, "files": {}, "players": {}}
    ledger["mission"] = mission
    ledger["since"] = since

    logs = find_logs(args.logs)
    ordered = sorted(logs.items(), key=lambda kv: (log_start(kv[1]) or datetime.max, kv[0]))
    ingested = 0
    for name, path in ordered:
        start = log_start(path)
        if start is None:
            print(f"skipped {rel(path)}: no AdminLog header")
            continue
        if since and start.date().isoformat() < since:
            continue
        size = os.path.getsize(path)
        known = ledger["files"].get(name)
        if known:
            if size > known["bytes"]:
                print(f"warning: {name} is larger than when it was ingested; run --rebuild to read it again")
            continue
        first, last = ingest(ledger, path)
        ledger["files"][name] = {
            "start": fmt_time(start),
            "end": fmt_time(last or start),
            "bytes": size,
        }
        ingested += 1
        print(f"ingested {name}  {fmt_time(start)} .. {fmt_time(last or start)}")
    if not ledger["files"]:
        sys.exit(f"no admin logs under {rel(args.logs)}; nothing to build a board from")

    save_ledger(ledger, args.ledger)
    as_of = max(f["end"] for f in ledger["files"].values()).replace("T", " ")
    lines = board_lines(ledger)
    render(lines, as_of, out_path)

    print(f"\n{ingested} new log(s), {len(ledger['files'])} in the ledger, board as of {as_of}")
    for pid, p in sorted(ledger["players"].items(), key=lambda kv: -kv[1]["alive_seconds"]):
        print(f"  {p['name']:<20} alive {fmt_duration(p['alive_seconds']):<12} since {p['since']}  "
              f"deaths {len(p['deaths'])}  resets {len(p['resets'])}  last seen {p['last_seen']}")
    print(f"\n{rel(out_path)}:")
    for line in lines:
        print(f"  {line}")
    if not lines:
        print("  (no character has logged time yet; the file carries no messages)")


if __name__ == "__main__":
    main()
